// Copies the Worker (../../worker/index.js) into src/ before tsc runs, so the package compiles and
// ships the exact code the Cloudflare Worker runs. src/sso-local.ts runs it in-process for a
// self-hosted server. The copy is generated and gitignored: edit worker/index.js, never the copy.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "..", "..", "worker", "index.js");
const target = join(here, "..", "src", "sso-worker-handler.js");
const header =
  "// GENERATED by scripts/copy-worker.mjs from worker/index.js. Do not edit; edit the Worker.\n";
writeFileSync(target, header + readFileSync(source, "utf8"));
